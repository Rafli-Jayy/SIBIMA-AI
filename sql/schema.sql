BEGIN;
SET LOCAL search_path TO public;
-- Proteksi: file ini hanya boleh dijalankan pada DB baru bernama sibima_db.
DO $$
BEGIN
    IF current_database() <> 'sibima_db' THEN
        RAISE EXCEPTION 'DB tujuan salah. Gunakan sibima_db, bukan %', current_database();
    END IF;
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_class c
               JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
               WHERE n.nspname='public' AND c.relname IN ('pengguna','users')) THEN
        RAISE EXCEPTION 'Database tidak kosong. Schema SIBIMA-AI tidak boleh diulang.';
    END IF;
END $$;


-- Extension digunakan untuk mencegah bentrok jadwal Tutor/Ruangan.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 1. Tipe data ENUM sesuai nilai yang digunakan SIBIMA.
CREATE TYPE user_role AS ENUM ('admin', 'tutor', 'siswa');
CREATE TYPE user_status AS ENUM (
    'belum_verifikasi', 'menunggu_konfirmasi', 'aktif', 'ditolak', 'nonaktif'
);
CREATE TYPE otp_purpose AS ENUM ('register', 'reset_password', 'login');
CREATE TYPE program_status AS ENUM ('buka', 'tutup');
CREATE TYPE nama_hari AS ENUM (
    'senin', 'selasa', 'rabu', 'kamis', 'jumat', 'sabtu', 'minggu'
);
CREATE TYPE enrollment_status AS ENUM (
    'menunggu', 'aktif', 'ditolak', 'batal', 'selesai', 'menunggu_pembayaran'
);
CREATE TYPE session_status AS ENUM (
    'terlaksana', 'batal', 'perlu_laporan', 'selesai'
);
CREATE TYPE attendance_status AS ENUM ('H', 'I', 'S', 'A');
CREATE TYPE grade_type AS ENUM ('tugas', 'kuis', 'uts', 'uas');
CREATE TYPE invoice_status AS ENUM ('belum_dibayar', 'lunas', 'batal');
CREATE TYPE payment_status AS ENUM (
    'menunggu_pembayaran', 'menunggu_konfirmasi',
    'lunas', 'ditolak', 'gagal', 'direfund'
);

-- Untuk validasi bentrok jam pada hari yang sama.
CREATE TYPE timerange AS RANGE (subtype = TIME WITHOUT TIME ZONE);

-- Urutan nomor invoice: dibuat mandiri agar schema ini bisa berdiri sendiri.
CREATE SEQUENCE nomor_invoice_seq START WITH 1;
CREATE FUNCTION buat_nomor_invoice() RETURNS TEXT
LANGUAGE SQL VOLATILE AS $$
    SELECT 'INV-' || to_char(CURRENT_TIMESTAMP, 'YYYYMMDD') || '-' ||
           lpad(nextval('nomor_invoice_seq')::TEXT, 4, '0');
$$;

-- ============================================================================
-- 01. PENGGUNA
-- ============================================================================
CREATE TABLE pengguna (
    id_pengguna            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username               VARCHAR(30) NOT NULL,
    email                  VARCHAR(120) NOT NULL,
    nama_lengkap           VARCHAR(100) NOT NULL,
    password_hash          TEXT NOT NULL,
    role                   user_role NOT NULL,
    status                 user_status NOT NULL DEFAULT 'belum_verifikasi',
    email_verified         BOOLEAN NOT NULL DEFAULT FALSE,
    failed_attempts        SMALLINT NOT NULL DEFAULT 0,
    locked_until           TIMESTAMPTZ,
    must_change_password   BOOLEAN NOT NULL DEFAULT FALSE,
    id_pengguna_penyetuju  INTEGER,
    approved_at            TIMESTAMPTZ,
    reject_reason          TEXT,
    last_login             TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_pengguna_id_role UNIQUE (id_pengguna, role),
    CONSTRAINT fk_pengguna_penyetuju FOREIGN KEY (id_pengguna_penyetuju)
        REFERENCES pengguna (id_pengguna),
    CONSTRAINT ck_pengguna_email CHECK (
        email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    ),
    CONSTRAINT ck_pengguna_username CHECK (username ~ '^[a-zA-Z0-9_]{4,30}$'),
    CONSTRAINT ck_pengguna_gagal_login CHECK (failed_attempts >= 0)
);

-- ============================================================================
-- 02. SISWA
-- ============================================================================
CREATE TABLE siswa (
    id_pengguna   INTEGER PRIMARY KEY,
    role          user_role NOT NULL DEFAULT 'siswa',
    nis           VARCHAR(10) UNIQUE,
    jenjang       VARCHAR(20),
    sekolah       VARCHAR(100),
    no_hp         VARCHAR(20),
    nama_wali     VARCHAR(100),
    CONSTRAINT ck_siswa_role CHECK (role = 'siswa'),
    CONSTRAINT fk_siswa_pengguna FOREIGN KEY (id_pengguna, role)
        REFERENCES pengguna (id_pengguna, role) ON DELETE CASCADE
);

-- ============================================================================
-- 03. TUTOR
-- ============================================================================
CREATE TABLE tutor (
    id_pengguna  INTEGER PRIMARY KEY,
    role         user_role NOT NULL DEFAULT 'tutor',
    kode_tutor   VARCHAR(10) UNIQUE,
    keahlian     VARCHAR(150),
    no_hp        VARCHAR(20),
    CONSTRAINT ck_tutor_role CHECK (role = 'tutor'),
    CONSTRAINT fk_tutor_pengguna FOREIGN KEY (id_pengguna, role)
        REFERENCES pengguna (id_pengguna, role) ON DELETE CASCADE
);

-- ============================================================================
-- 04. PROGRAM BIMBEL
-- ============================================================================
CREATE TABLE program_bimbel (
    id_program      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode            VARCHAR(10) NOT NULL UNIQUE,
    nama            VARCHAR(100) NOT NULL,
    jenjang         VARCHAR(20) NOT NULL,
    deskripsi       TEXT,
    harga_bulanan   NUMERIC(12,2) NOT NULL,
    kuota           SMALLINT NOT NULL,
    status          program_status NOT NULL DEFAULT 'buka',
    bobot_tugas     SMALLINT NOT NULL DEFAULT 30,
    bobot_kuis      SMALLINT NOT NULL DEFAULT 20,
    bobot_uts       SMALLINT NOT NULL DEFAULT 20,
    bobot_uas       SMALLINT NOT NULL DEFAULT 30,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_program_harga CHECK (harga_bulanan >= 0),
    CONSTRAINT ck_program_kuota CHECK (kuota > 0),
    CONSTRAINT ck_program_bobot_tugas CHECK (bobot_tugas BETWEEN 0 AND 100),
    CONSTRAINT ck_program_bobot_kuis CHECK (bobot_kuis BETWEEN 0 AND 100),
    CONSTRAINT ck_program_bobot_uts CHECK (bobot_uts BETWEEN 0 AND 100),
    CONSTRAINT ck_program_bobot_uas CHECK (bobot_uas BETWEEN 0 AND 100),
    CONSTRAINT ck_program_bobot_total CHECK (
        bobot_tugas + bobot_kuis + bobot_uts + bobot_uas = 100
    )
);

-- ============================================================================
-- 05. RUANGAN
-- ============================================================================
CREATE TABLE ruangan (
    id_ruangan  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(30) NOT NULL UNIQUE,
    kapasitas   SMALLINT NOT NULL,
    aktif       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_ruangan_kapasitas CHECK (kapasitas > 0)
);

-- ============================================================================
-- 06. JADWAL KELAS
-- ============================================================================
CREATE TABLE jadwal_kelas (
    id_jadwal          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_program         INTEGER NOT NULL,
    id_tutor           INTEGER NOT NULL,
    id_ruangan         INTEGER NOT NULL,
    hari               nama_hari NOT NULL,
    jam_mulai          TIME NOT NULL,
    jam_selesai        TIME NOT NULL,
    aktif              BOOLEAN NOT NULL DEFAULT TRUE,
    notif_monitor_from TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_jadwal_program FOREIGN KEY (id_program)
        REFERENCES program_bimbel (id_program),
    CONSTRAINT fk_jadwal_tutor FOREIGN KEY (id_tutor)
        REFERENCES tutor (id_pengguna),
    CONSTRAINT fk_jadwal_ruangan FOREIGN KEY (id_ruangan)
        REFERENCES ruangan (id_ruangan),
    CONSTRAINT ck_jadwal_jam CHECK (jam_mulai < jam_selesai),
    CONSTRAINT ex_jadwal_bentrok_ruangan EXCLUDE USING gist (
        id_ruangan WITH =, hari WITH =, timerange(jam_mulai, jam_selesai) WITH &&
    ) WHERE (aktif),
    CONSTRAINT ex_jadwal_bentrok_tutor EXCLUDE USING gist (
        id_tutor WITH =, hari WITH =, timerange(jam_mulai, jam_selesai) WITH &&
    ) WHERE (aktif)
);

-- ============================================================================
-- 07. PERTEMUAN KELAS
-- ============================================================================
CREATE TABLE pertemuan_kelas (
    id_pertemuan  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_jadwal     INTEGER NOT NULL,
    tanggal       DATE NOT NULL,
    pertemuan_ke  SMALLINT NOT NULL,
    topik         VARCHAR(150),
    ringkasan     TEXT,
    status        session_status NOT NULL DEFAULT 'perlu_laporan',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    alasan_batal  VARCHAR(500),
    selesai_at    TIMESTAMPTZ,
    CONSTRAINT uq_pertemuan_ke UNIQUE (id_jadwal, pertemuan_ke),
    CONSTRAINT uq_pertemuan_tanggal UNIQUE (id_jadwal, tanggal),
    CONSTRAINT fk_pertemuan_jadwal FOREIGN KEY (id_jadwal)
        REFERENCES jadwal_kelas (id_jadwal),
    CONSTRAINT ck_pertemuan_ke CHECK (pertemuan_ke > 0)
);

-- ============================================================================
-- 08. PENDAFTARAN
-- ============================================================================
CREATE TABLE pendaftaran (
    id_pendaftaran        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_siswa              INTEGER NOT NULL,
    id_program            INTEGER NOT NULL,
    status                enrollment_status NOT NULL DEFAULT 'menunggu',
    alasan_tolak          TEXT,
    id_pengguna_pemroses  INTEGER,
    processed_at          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_pendaftaran_siswa FOREIGN KEY (id_siswa)
        REFERENCES siswa (id_pengguna),
    CONSTRAINT fk_pendaftaran_program FOREIGN KEY (id_program)
        REFERENCES program_bimbel (id_program),
    CONSTRAINT fk_pendaftaran_pemroses FOREIGN KEY (id_pengguna_pemroses)
        REFERENCES pengguna (id_pengguna)
);

-- ============================================================================
-- 09. KEHADIRAN
-- ============================================================================
CREATE TABLE kehadiran (
    id_pertemuan    INTEGER NOT NULL,
    id_siswa        INTEGER NOT NULL,
    status          attendance_status NOT NULL,
    keterangan      VARCHAR(200),
    dicatat_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_pendaftaran  INTEGER,
    CONSTRAINT pk_kehadiran PRIMARY KEY (id_pertemuan, id_siswa),
    CONSTRAINT fk_kehadiran_pertemuan FOREIGN KEY (id_pertemuan)
        REFERENCES pertemuan_kelas (id_pertemuan) ON DELETE CASCADE,
    CONSTRAINT fk_kehadiran_siswa FOREIGN KEY (id_siswa)
        REFERENCES siswa (id_pengguna),
    CONSTRAINT fk_kehadiran_pendaftaran FOREIGN KEY (id_pendaftaran)
        REFERENCES pendaftaran (id_pendaftaran)
);

-- ============================================================================
-- 10. NILAI
-- ============================================================================
CREATE TABLE nilai (
    id_nilai             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pendaftaran       INTEGER NOT NULL,
    jenis                grade_type NOT NULL,
    judul                VARCHAR(100),
    nilai                NUMERIC(5,2) NOT NULL,
    tanggal              DATE NOT NULL DEFAULT CURRENT_DATE,
    id_tutor_penginput   INTEGER,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_nilai_pendaftaran FOREIGN KEY (id_pendaftaran)
        REFERENCES pendaftaran (id_pendaftaran),
    CONSTRAINT fk_nilai_tutor FOREIGN KEY (id_tutor_penginput)
        REFERENCES tutor (id_pengguna),
    CONSTRAINT ck_nilai_rentang CHECK (nilai BETWEEN 0 AND 100)
);

-- ============================================================================
-- 11. TAGIHAN
-- ============================================================================
CREATE TABLE tagihan (
    id_tagihan      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    no_invoice      VARCHAR(30) NOT NULL DEFAULT buat_nomor_invoice(),
    id_pendaftaran  INTEGER NOT NULL,
    periode         DATE NOT NULL,
    jumlah          NUMERIC(12,2) NOT NULL,
    jatuh_tempo     DATE NOT NULL,
    status          invoice_status NOT NULL DEFAULT 'belum_dibayar',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_tagihan_nomor UNIQUE (no_invoice),
    CONSTRAINT uq_tagihan_pendaftaran_periode UNIQUE (id_pendaftaran, periode),
    CONSTRAINT fk_tagihan_pendaftaran FOREIGN KEY (id_pendaftaran)
        REFERENCES pendaftaran (id_pendaftaran),
    CONSTRAINT ck_tagihan_jumlah CHECK (jumlah >= 0),
    CONSTRAINT ck_tagihan_periode CHECK (EXTRACT(DAY FROM periode) = 1)
);

-- ============================================================================
-- 12. PEMBAYARAN
-- ============================================================================
CREATE TABLE pembayaran (
    id_pembayaran         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tagihan            INTEGER NOT NULL,
    kode_bayar            VARCHAR(30) NOT NULL UNIQUE,
    jumlah                NUMERIC(12,2) NOT NULL,
    status                payment_status NOT NULL DEFAULT 'menunggu_pembayaran',
    paid_at               TIMESTAMPTZ,
    id_pengguna_pemroses  INTEGER,
    processed_at          TIMESTAMPTZ,
    alasan_tolak          TEXT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_pembayaran_tagihan FOREIGN KEY (id_tagihan)
        REFERENCES tagihan (id_tagihan),
    CONSTRAINT fk_pembayaran_pemroses FOREIGN KEY (id_pengguna_pemroses)
        REFERENCES pengguna (id_pengguna),
    CONSTRAINT ck_pembayaran_jumlah CHECK (jumlah > 0)
);

-- ============================================================================
-- 13. PENGEMBALIAN PEMBAYARAN
-- ============================================================================
CREATE TABLE pengembalian_pembayaran (
    id_pengembalian  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pembayaran    INTEGER NOT NULL UNIQUE,
    kode_refund      VARCHAR(40) NOT NULL UNIQUE,
    jumlah           NUMERIC(12,2) NOT NULL,
    alasan           TEXT NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'berhasil',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_pengembalian_pembayaran FOREIGN KEY (id_pembayaran)
        REFERENCES pembayaran (id_pembayaran),
    CONSTRAINT ck_pengembalian_jumlah CHECK (jumlah > 0),
    CONSTRAINT ck_pengembalian_status CHECK (status IN ('berhasil', 'gagal'))
);

-- ============================================================================
-- 14. PENGUMUMAN
-- ============================================================================
CREATE TABLE pengumuman (
    id_pengumuman         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul                 VARCHAR(150) NOT NULL,
    isi                   TEXT NOT NULL,
    id_pengguna_pembuat   INTEGER NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    archived_at           TIMESTAMPTZ,
    id_pengguna_penerima  INTEGER,
    sumber                VARCHAR(20) NOT NULL DEFAULT 'admin',
    kategori              VARCHAR(30) NOT NULL DEFAULT 'umum',
    event_key             TEXT,
    expires_at            TIMESTAMPTZ,
    id_program            INTEGER,
    batch_key             TEXT,
    id_pengguna_aktor     INTEGER,
    related_type          VARCHAR(30),
    related_id            INTEGER,
    CONSTRAINT fk_pengumuman_pembuat FOREIGN KEY (id_pengguna_pembuat)
        REFERENCES pengguna (id_pengguna),
    CONSTRAINT fk_pengumuman_penerima FOREIGN KEY (id_pengguna_penerima)
        REFERENCES pengguna (id_pengguna) ON DELETE CASCADE,
    CONSTRAINT fk_pengumuman_program FOREIGN KEY (id_program)
        REFERENCES program_bimbel (id_program),
    CONSTRAINT fk_pengumuman_aktor FOREIGN KEY (id_pengguna_aktor)
        REFERENCES pengguna (id_pengguna)
);

-- ============================================================================
-- 15. TARGET PENGUMUMAN
-- ============================================================================
CREATE TABLE target_pengumuman (
    id_pengumuman  INTEGER NOT NULL,
    target_role    user_role NOT NULL,
    CONSTRAINT pk_target_pengumuman PRIMARY KEY (id_pengumuman, target_role),
    CONSTRAINT fk_target_pengumuman FOREIGN KEY (id_pengumuman)
        REFERENCES pengumuman (id_pengumuman) ON DELETE CASCADE,
    CONSTRAINT ck_target_pengumuman_role CHECK (target_role IN ('siswa', 'tutor'))
);

-- ============================================================================
-- 16. PEMBACAAN PENGUMUMAN
-- ============================================================================
CREATE TABLE pembacaan_pengumuman (
    id_pengumuman  INTEGER NOT NULL,
    id_pengguna    INTEGER NOT NULL,
    read_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    archived_at    TIMESTAMPTZ,
    CONSTRAINT pk_pembacaan_pengumuman PRIMARY KEY (id_pengumuman, id_pengguna),
    CONSTRAINT fk_pembacaan_pengumuman FOREIGN KEY (id_pengumuman)
        REFERENCES pengumuman (id_pengumuman) ON DELETE CASCADE,
    CONSTRAINT fk_pembacaan_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna (id_pengguna) ON DELETE CASCADE
);

-- ============================================================================
-- 17. KODE OTP
-- ============================================================================
CREATE TABLE kode_otp (
    id_otp       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna  INTEGER NOT NULL,
    code_hash    TEXT NOT NULL,
    purpose      otp_purpose NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    attempts     SMALLINT NOT NULL DEFAULT 0,
    used_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_kode_otp_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna (id_pengguna) ON DELETE CASCADE,
    CONSTRAINT ck_kode_otp_percobaan CHECK (attempts >= 0)
);

-- ============================================================================
-- 18. LOG AKTIVITAS
-- ============================================================================
CREATE TABLE log_aktivitas (
    id_log       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna  INTEGER,
    aksi         VARCHAR(60) NOT NULL,
    detail       TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_log_pengguna FOREIGN KEY (id_pengguna)
        REFERENCES pengguna (id_pengguna)
);

-- ============================================================================
-- INDEKS PENDUKUNG DAN ATURAN UNIK KONDISIONAL
-- ============================================================================
-- Identitas akun unik tanpa membedakan huruf besar-kecil.
CREATE UNIQUE INDEX uq_pengguna_username_ci ON pengguna (LOWER(username));
CREATE UNIQUE INDEX uq_pengguna_email_ci ON pengguna (LOWER(email));
CREATE INDEX idx_pengguna_status_role ON pengguna (status, role);

-- Satu siswa tidak boleh memiliki lebih dari satu pendaftaran berjalan
-- pada program yang sama.
CREATE UNIQUE INDEX uq_pendaftaran_berjalan
    ON pendaftaran (id_siswa, id_program)
    WHERE status IN ('menunggu_pembayaran', 'menunggu', 'aktif');
CREATE INDEX idx_pendaftaran_program_status ON pendaftaran (id_program, status);

CREATE INDEX idx_jadwal_program ON jadwal_kelas (id_program);
CREATE INDEX idx_jadwal_tutor_hari ON jadwal_kelas (id_tutor, hari);
CREATE INDEX idx_kehadiran_siswa ON kehadiran (id_siswa);
CREATE INDEX idx_kehadiran_pendaftaran ON kehadiran (id_pendaftaran)
    WHERE id_pendaftaran IS NOT NULL;
CREATE INDEX idx_nilai_pendaftaran_jenis ON nilai (id_pendaftaran, jenis);
CREATE INDEX idx_tagihan_status_tenggat ON tagihan (status, jatuh_tempo);
CREATE INDEX idx_pembayaran_tagihan ON pembayaran (id_tagihan);
CREATE INDEX idx_pembayaran_status_waktu ON pembayaran (status, created_at);
CREATE INDEX idx_pengembalian_status_waktu
    ON pengembalian_pembayaran (status, created_at);
CREATE INDEX idx_kode_otp_pengguna_purpose
    ON kode_otp (id_pengguna, purpose, created_at DESC);
CREATE INDEX idx_log_aktivitas_waktu ON log_aktivitas (created_at DESC);
CREATE INDEX idx_pembacaan_pengguna ON pembacaan_pengumuman (id_pengguna, id_pengumuman);
CREATE INDEX idx_target_pengumuman_role ON target_pengumuman (target_role, id_pengumuman);
CREATE INDEX idx_pengumuman_aktif ON pengumuman (created_at DESC, id_pengumuman DESC)
    WHERE archived_at IS NULL;
CREATE UNIQUE INDEX uq_pengumuman_event_key ON pengumuman (event_key)
    WHERE event_key IS NOT NULL;
CREATE INDEX idx_pengumuman_penerima_waktu
    ON pengumuman (id_pengguna_penerima, created_at DESC)
    WHERE archived_at IS NULL AND id_pengguna_penerima IS NOT NULL;
CREATE INDEX idx_pengumuman_jenis_referensi ON pengumuman (related_type, related_id)
    WHERE related_type IS NOT NULL;
CREATE INDEX idx_pengumuman_batch_tutor ON pengumuman (id_pengguna_pembuat, batch_key)
    WHERE sumber = 'tutor' AND batch_key IS NOT NULL;
CREATE INDEX idx_pembacaan_arsip ON pembacaan_pengumuman (id_pengguna, archived_at);

COMMIT;
